/** Adreça (dins del banc $3A, $4000-$7FFF) d'una rutina del motor trobada pel patró, o -1. */
private fun gsAdr(rom: ByteArray, pat: String): Int {
    val i = gCercaW(rom, pat, GS_BANC * 0x4000, GS_BANC * 0x4000 + 0x4000)
    return if (i < 0) -1 else 0x4000 + (i - GS_BANC * 0x4000)
}

